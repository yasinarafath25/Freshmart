// Builds src/lib/photo-credits.ts from website-images/image-list.md (photographer/studio column).
// Run after updating the photo library: `npm run photos`.
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const md = readFileSync("website-images/image-list.md", "utf8");
const rows = [];
for (const line of md.split("\n")) {
  const m = line.match(/^\|\s*`([^`]+\.jpg)`\s*\|\s*([^|]*)\|\s*([^|]*)\|\s*([^|]*)\|/);
  if (m && !/ফটোগ্রাফার|Photographer/.test(m[4])) rows.push({ file: m[1], name: m[3].trim(), credit: m[4].trim() });
}
const byCredit = {};
for (const r of rows) (byCredit[r.credit] ??= []).push(r.name);

writeFileSync(
  "src/lib/photo-credits.ts",
  `// Generated by scripts/photo-credits.mjs from website-images/image-list.md — do not edit by hand.\nexport const PHOTO_CREDITS: { credit: string; subjects: string[] }[] = ${JSON.stringify(
    Object.entries(byCredit)
      .sort((a, b) => b[1].length - a[1].length)
      .map(([credit, subjects]) => ({ credit, subjects })),
    null,
    2,
  )};\n`,
);

// Keep public copies in sync with the owner's library.
for (const f of readdirSync("website-images").filter((f) => f.endsWith(".jpg"))) copyFileSync(`website-images/${f}`, `public/images/photos/${f}`);
console.log(`${rows.length} photos, ${Object.keys(byCredit).length} credits; public/images/photos synced`);
