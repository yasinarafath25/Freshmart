const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
export function toBnDigits(s: string): string {
  return s.replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]);
}

export const DICTS: Record<Lang, Dict> = { en, bn };

/** Formats a number for display (Bengali digits in bn). */
export function fmtNum(n: number | string, lang: Lang): string {
  const s = typeof n === "number" ? n.toLocaleString("en-IN") : n;
  return lang === "bn" ? toBnDigits(s) : s;
}

/** Money in minor units → "৳120" / "৳১২০". */
export function fmtMoney(minor: number, symbol: string, lang: Lang): string {
  const major = minor / 100;
  const s = major.toLocaleString("en-IN", { minimumFractionDigits: minor % 100 ? 2 : 0, maximumFractionDigits: 2 });
  return `${symbol}${lang === "bn" ? toBnDigits(s) : s}`;
}

/** Translates variant/unit labels like "1 kg", "Half dozen", "4 pieces". */
const UNIT_BN: [RegExp, string][] = [
  [/\bhalf dozen\b/gi, "হাফ ডজন"],
  [/\bdozen\b/gi, "ডজন"],
  [/\bkg\b/gi, "কেজি"],
  [/\bg\b/g, "গ্রাম"],
  [/\blitres?\b/gi, "লিটার"],
  [/\bml\b/gi, "মিলি"],
  [/\bpieces?\b/gi, "পিস"],
  [/\bbunch(es)?\b/gi, "আঁটি"],
  [/\bpacks?\b/gi, "প্যাকেট"],
  [/~/g, "প্রায় "],
];
export function unitLabel(text: string, lang: Lang): string {
  if (lang !== "bn") return text;
  let out = text;
  for (const [re, bnText] of UNIT_BN) out = out.replace(re, bnText);
  return toBnDigits(out);
}

export function fmtDate(d: Date | string, lang: Lang, opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "short", year: "numeric" }): string {
  const date = typeof d === "string" ? new Date(d + (d.length === 10 ? "T12:00:00Z" : "")) : d;
  return date.toLocaleDateString(lang === "bn" ? "bn-BD" : "en-GB", opts);
}

export function fmtDateTime(d: Date, lang: Lang): string {
  return d.toLocaleString(lang === "bn" ? "bn-BD" : "en-GB", { day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" });
}

/** "8:00 AM – 11:00 AM" → "সকাল ৮:০০ – ১১:০০" for display in Bangla (stored value stays English). */
export function slotLabel(slot: string, lang: Lang): string {
  if (lang !== "bn") return slot;
  let first = true;
  const out = slot.replace(/(\d{1,2}):(\d{2})\s*(AM|PM)/gi, (_, h: string, m: string, ap: string) => {
    let hour = Number(h) % 12;
    if (ap.toUpperCase() === "PM") hour += 12;
    const period = hour < 5 ? "রাত" : hour < 12 ? "সকাল" : hour < 15 ? "দুপুর" : hour < 18 ? "বিকেল" : hour < 20 ? "সন্ধ্যা" : "রাত";
    const text = `${Number(h)}:${m}`;
    const res = first ? `${period} ${text}` : `${period} ${text}`;
    first = false;
    return res;
  });
  return toBnDigits(out);
}
